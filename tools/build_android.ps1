param(
    [ValidateSet('Debug', 'ReleaseCompile', 'Release', 'Bundle')]
    [string]$Mode = 'ReleaseCompile',
    # Direct = APK with in-app self-update (noxbrain.com); Play = Google Play
    # build without self-update and REQUEST_INSTALL_PACKAGES.
    [ValidateSet('Direct', 'Play')]
    [string]$Store = 'Direct',
    [string]$JavaHome,
    [string]$SigningPropertiesPath
)
$ErrorActionPreference = 'Stop'
# An AAB is only ever uploaded to Google Play.
if ($Mode -eq 'Bundle' -and $Store -ne 'Play') { throw 'Bundle (AAB) is for Google Play only: use -Store Play.' }
$projectRoot = Split-Path -Parent $PSScriptRoot
$androidRoot = Join-Path $projectRoot 'mobile_app\android'
$previousJava = $env:JAVA_HOME
$previousOptions = $env:JAVA_TOOL_OPTIONS
$previousSigning = $env:NOXBRAIN_SIGNING_PROPERTIES
try {
    if ($JavaHome) { $env:JAVA_HOME = (Resolve-Path -LiteralPath $JavaHome).Path }
    elseif (-not $env:JAVA_HOME) { $env:JAVA_HOME = Split-Path -Parent (Split-Path -Parent (Get-Command java.exe).Source) }
    # Windows packaged apps can break Java's AF_UNIX loopback pipe. A missing
    # socket directory makes OpenJDK use its normal TCP loopback fallback.
    $unavailableSocketDirectory = Join-Path $androidRoot ('.gradle\no-af-unix-' + [guid]::NewGuid().ToString('N'))
    $env:JAVA_TOOL_OPTIONS = (($previousOptions + ' "-Djdk.net.unixdomain.tmpdir=' + $unavailableSocketDirectory + '"').Trim())
    if ($SigningPropertiesPath) { $env:NOXBRAIN_SIGNING_PROPERTIES = (Resolve-Path -LiteralPath $SigningPropertiesPath).Path }
    if ($Mode -in @('Release', 'Bundle') -and -not $env:NOXBRAIN_SIGNING_PROPERTIES -and -not (Test-Path -LiteralPath (Join-Path $androidRoot 'key.properties'))) {
        throw 'Provide the existing signing key.properties using -SigningPropertiesPath. No signing key is generated by this script.'
    }
    Push-Location -LiteralPath (Join-Path $projectRoot 'mobile_app')
    try {
        & flutter.bat pub get
        if ($LASTEXITCODE -ne 0) { throw 'Flutter dependency/plugin registration failed.' }
    } finally { Pop-Location }
    # Gradle reads the app version from local.properties, which only
    # 'flutter build' updates; copy it from pubspec.yaml so the APK/AAB never
    # carries the previous version.
    $pubspec = Get-Content -LiteralPath (Join-Path $projectRoot 'mobile_app\pubspec.yaml')
    $versionLine = $pubspec | Where-Object { $_ -match '^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$' } | Select-Object -First 1
    if (-not $versionLine) { throw 'pubspec.yaml has no version: X.Y.Z+CODE line.' }
    $null = $versionLine -match '^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$'
    $versionName = $Matches[1]
    $versionCode = $Matches[2]
    $localProperties = Join-Path $androidRoot 'local.properties'
    [string[]]$lines = @(Get-Content -LiteralPath $localProperties | Where-Object { $_ -notmatch '^flutter\.version(Name|Code)=' })
    $lines += "flutter.versionName=$versionName"
    $lines += "flutter.versionCode=$versionCode"
    Set-Content -LiteralPath $localProperties -Value $lines -Encoding ASCII
    Write-Host "App version for this build: $versionName ($versionCode)"
    [string[]]$buildTasks = @(switch ($Mode) {
        'Debug' { @(':app:assembleDebug') }
        'ReleaseCompile' { @(':app:compileReleaseKotlin', ':app:compileFlutterBuildRelease') }
        'Release' { @(':app:assembleRelease') }
        'Bundle' { @(':app:bundleRelease') }
    })
    # Flutter's Gradle plugin reads dart-defines as comma-separated Base64.
    [string[]]$storeArgs = @()
    if ($Store -eq 'Play') {
        $define = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes('NOXBRAIN_STORE=play'))
        $storeArgs = @('-PnoxbrainStore=play', "-Pdart-defines=$define")
    }
    Push-Location -LiteralPath $androidRoot
    try {
        & .\gradlew.bat @buildTasks @storeArgs --no-daemon --console=plain
        if ($LASTEXITCODE -ne 0) { throw "Android $Mode ($Store) build failed ($LASTEXITCODE)." }
    } finally { Pop-Location }
    if ($Mode -eq 'Bundle') { Write-Host 'AAB: solar_monitor_app\build\app\outputs\bundle\release\app-release.aab (upload to Google Play only).' }
    elseif ($Mode -eq 'Release' -and $Store -eq 'Play') { Write-Host 'Play test APK built. Do NOT package it with package_release.py app (it has no self-update).' }
} finally {
    $env:JAVA_HOME = $previousJava
    $env:JAVA_TOOL_OPTIONS = $previousOptions
    $env:NOXBRAIN_SIGNING_PROPERTIES = $previousSigning
}
